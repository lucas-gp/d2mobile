/** Parmi les fichiers choisis : archives audio reçues, absentes, ce qu'elles apportent, taille à copier */
export function audioReport(files: { name: string; size: number }[], invalid: string[] = []): AudioReport {
  const bad = new Set(invalid.map((n) => n.toLowerCase()));
  const byName = new Map<string, { name: string; size: number }>();
  for (const f of files) {
    const n = f.name.toLowerCase();
    if (!isAudioMpq(n)) continue;
    const prev = byName.get(n);
    if (!prev || f.size > prev.size) byName.set(n, f);
  }
  const present: string[] = [];
  const invalidOut: string[] = [];
  const missing: string[] = [];
  const gives: string[] = [];
  const lacks: string[] = [];
  let bytes = 0;
  for (const a of AUDIO_MPQ) {
    const f = byName.get(a.name);
    if (f && !bad.has(a.name) && f.size >= 1024) {
      present.push(a.name);
      bytes += f.size;
      gives.push(a.gives);
    } else if (f) {
      invalidOut.push(f.name);
      lacks.push(a.gives);
    } else {
      missing.push(a.name);
      lacks.push(a.gives);
    }
  }
  return { present, missing, invalid: invalidOut, bytes, gives, lacks };
}

/** Archives audio d'une sélection (plus gros fichier en cas de doublon) */
export function audioMpq<T extends { name: string; size: number }>(files: T[]): T[] {
  const best = new Map<string, T>();
  for (const f of files) {
    const n = f.name.toLowerCase();
    if (!isAudioMpq(n)) continue;
    const prev = best.get(n);
    if (!prev || f.size > prev.size) best.set(n, f);
  }
  return [...best.values()];
}

