/** Mesures de la phase 2 (Chromium, PC) : secondes et octets par type d'asset, palier unique */
export const COST = {
  /** unité : hi + lo, mesuré sur PC en phase 2 (voir BROWSER.md) */
  unit: { sec: 0.7, bytes: 1.25e6 },
  part: { sec: 1.5, bytes: 0.33e6 },
  prop: { sec: 0.26, bytes: 0.03e6 },
  ground: { sec: 0.42, bytes: 0.23e6 },
  fx: { sec: 0.08, bytes: 0.1e6 },
  extras: { sec: 13, bytes: 8.4e6 },
} as const;

export interface CatalogCounts {
  units: number;
  parts: number;
  props: number;
  fx: number;
  grounds: number;
}

/** Durée (s) et stockage (octets) pour tout générer au palier donné, `speed` = 1 pour un PC, 3 à 5 pour un téléphone */
export function estimateAll(c: CatalogCounts, tier: Tier | 'both', speed = 1): { seconds: number; bytes: number } {
  // mesures (PC, un Worker) : tout en lo = 1 146 s et 222 Mo contre 1 249 s et 569 Mo pour hi + lo : la composition des images domine, pas l'encodage
  const t = tier === 'both' ? { time: 1, size: 1 } : tier === 'lo' ? { time: 0.92, size: 0.4 } : { time: 0.97, size: 0.65 };
  const sec = c.units * COST.unit.sec + c.parts * COST.part.sec + c.props * COST.prop.sec + c.grounds * COST.ground.sec + c.fx * COST.fx.sec;
  const bytes = c.units * COST.unit.bytes + c.parts * COST.part.bytes + c.props * COST.prop.bytes + c.grounds * COST.ground.bytes + c.fx * COST.fx.bytes;
  return { seconds: Math.round((sec * t.time + COST.extras.sec) * speed), bytes: Math.round(bytes * t.size + COST.extras.bytes) };
}

/** Taille totale des MPQ à copier dans OPFS et marge d'espace libre nécessaire pour y ajouter les graphismes */
export function copyPlan(sizes: number[], quota: number | null, usage: number | null, reserve = 150e6): { need: number; free: number | null; fits: boolean } {
  const need = sizes.reduce((a, b) => a + b, 0) + reserve;
  const free = quota === null || usage === null ? null : Math.max(0, quota - usage);
  return { need, free, fits: free === null ? true : free >= need };
}

/** Appareil « modeste » : tactile avec peu de mémoire ou de cœurs ; sert à choisir le palier `lo` seul par défaut */
export function isModestDevice(d: { coarse: boolean; memoryGb?: number; cores?: number; width?: number }): boolean {
  if (d.coarse) return true;
  if ((d.memoryGb ?? 8) <= 4) return true;
  if ((d.cores ?? 8) <= 4) return true;
  return false;
}

/** Mémoire déclarée (Go) en dessous de laquelle « Auto » choisit le palier économe : la haute résolution risquerait de faire échouer le navigateur */
const WEAK_DEVICE_GB = 2;
/** Espace libre (octets) sous lequel « Auto » choisit le palier économe : la haute résolution prend environ 1,6 fois plus de place */
export const TIGHT_STORAGE_FREE = 700e6;

/**
 * Palier de génération. Réglage explicite : respecté. « Auto » = HAUTE sur tous les appareils (téléphones compris : le budget de textures de
 * l'affichage rabaisse planche par planche et carte par carte ce qui ne tiendrait pas), sauf appareil très faible (≤ 2 Go déclarés) ou
 * stockage presque plein (< 700 Mo libres) : économe.
 */
export function chooseGenTier(setting: 'auto' | 'lo' | 'hi', memoryGb?: number, tightStorage = false): Tier {
  if (setting === 'lo' || setting === 'hi') return setting;
  if (memoryGb !== undefined && memoryGb <= WEAK_DEVICE_GB) return 'lo';
  return tightStorage ? 'lo' : 'hi';
}

/** Pourquoi « Auto » a choisi l'économe (null : haute) */
export function autoTierReason(memoryGb?: number, tightStorage = false): 'weak' | 'storage' | null {
  if (memoryGb !== undefined && memoryGb <= WEAK_DEVICE_GB) return 'weak';
  return tightStorage ? 'storage' : null;
}
