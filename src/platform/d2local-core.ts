/** Empreinte de l'ensemble : ordre et casse des noms sans effet */
export function setFingerprint(files: FileFingerprint[]): string {
  return [...files]
    .map((f) => `${f.name.toLowerCase()}:${f.size}:${f.fp}`)
    .sort()
    .join('|');
}

export interface LocalMeta {
  gen: number;
  /** empreinte de l'ensemble de MPQ qui a produit le cache */
  fp: string;
  files: FileFingerprint[];
  created: number;
}

/** Raison pour laquelle le cache généré n'est plus valable, ou null */
export function staleReason(meta: LocalMeta | null, fp: string | null, gen = GENERATOR_VERSION): 'generator' | 'files' | null {
  if (!meta) return null;
  if (meta.gen !== gen) return 'generator';
  if (fp !== null && meta.fp !== fp) return 'files';
  return null;
}

