export const emptyManifest = (): LocalManifest => ({ version: 1, source: 'd2local', sheets: {}, tiles: {} });

export function tiersOf(e: Pick<ManifestEntry, 'tiers'> | undefined | null): Tier[] {
  return e ? (e.tiers?.length ? e.tiers : ['hi', 'lo']) : [];
}

export function hasTier(e: Pick<ManifestEntry, 'tiers'> | undefined | null, t: Tier): boolean {
  return tiersOf(e).includes(t);
}

/**
 * Fusionne l'entrée d'un asset qu'on vient de générer (un ou deux paliers) avec celle déjà en cache : le palier absent garde une estimation
 * de mémoire (hi ≈ 4 × lo) pour le budget de textures ; `tiers` disparaît quand les deux paliers existent.
 */
export function mergeEntry(prev: ManifestEntry | undefined, fresh: ManifestEntry, made: readonly Tier[]): ManifestEntry {
  const have = new Set<Tier>([...(prev ? tiersOf(prev) : []), ...made]);
  const out: ManifestEntry = { ...fresh };
  for (const t of ['hi', 'lo'] as const) {
    if (made.includes(t)) out[t] = fresh[t];
    else if (prev && hasTier(prev, t)) out[t] = prev[t];
    else out[t] = { bytes: 0, gpu: 0 };
  }
  // estimations pour un palier absent
  if (!have.has('hi') && have.has('lo')) out.hi = { bytes: 0, gpu: out.lo.gpu * 4 };
  if (!have.has('lo') && have.has('hi')) out.lo = { bytes: 0, gpu: Math.ceil(out.hi.gpu / 4) };
  if (have.size >= 2) delete out.tiers;
  else out.tiers = [...have];
  return out;
}

