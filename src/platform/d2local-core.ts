export interface OnboardInput {
  /** nature de la version : dossier en clair (développement), dossier chiffré, ou rien */
  build: 'plain' | 'enc' | 'off';
  /** version publique (D2_PUBLIC=1) ou écran forcé (?d2=choose) */
  publicOrForced: boolean;
  /** un mot de passe est mémorisé (mode chiffré) */
  savedPassword: boolean;
  /** « Sans les graphismes D2 » mémorisé d'une session précédente (mode chiffré) */
  refused: boolean;
  /** « Jouer avec les graphismes de remplacement » choisi dans cet onglet */
  sessionSkip: boolean;
  /** réglage « graphismes locaux » actif */
  localFlag: boolean;
  /** les fichiers (copie ou poignées) ou des graphismes générés sont déjà là */
  haveAssets: boolean;
}

/**
 * Que montrer au lancement ? `none` : rien (mot de passe déjà mémorisé, développement, joueur qui a déjà tout) ;
 * `choose` : l'écran de choix (mot de passe si la version l'embarque, import) ; `import` : directement l'import (réglage actif mais
 * fichiers à fournir à nouveau). Le mode chiffré avec mot de passe est traité par `askPassword` (même écran).
 */
export function onboardAction(i: OnboardInput): 'none' | 'choose' | 'import' {
  if (i.build === 'plain') return 'none';
  if (i.build === 'enc' && (i.savedPassword || i.refused)) return 'none';
  if (i.sessionSkip) return 'none';
  if (i.localFlag) return i.haveAssets ? 'none' : 'import';
  return i.build === 'enc' || i.publicOrForced ? 'choose' : 'none';
}

