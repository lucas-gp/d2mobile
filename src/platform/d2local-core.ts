/** Lot 317: the maps generated by an earlier revision of their export (`MAP_REVISIONS`): to be generated again, alone */
export function staleMaps(m: Pick<LocalManifest, 'maps'>, rev: (id: string) => number = mapRevision): string[] {
  return Object.entries(m.maps ?? {})
    .filter(([id, e]) => (e.rev ?? 0) < rev(id))
    .map(([id]) => id);
}

