export interface CopyState {
  /**
   * `crc` : CRC32 de chaque morceau (COPY_CHUNK) de la source, noté à l'écriture ; `ver` : la copie a été relue et comparée à la source
   * morceau par morceau (sinon : copie ancienne ou interrompue, intégrité inconnue).
   */
  [name: string]: { size: number; done: number; fp?: string; crc?: number[]; ver?: boolean; chk?: ArchiveCheck };
}

/** Résultat de la vérification d'un fichier copié (relecture de la copie contre les empreintes enregistrées à la copie) */
type FileIntegrity = 'ok' | 'unverified' | 'damaged' | 'missing' | 'size';
export interface IntegrityFile {
  name: string;
  status: FileIntegrity;
  /** morceau (8 Mo) et décalage du premier écart */
  chunk?: number;
  offset?: number;
}

/** Erreurs typiques d'une donnée corrompue (format MPQ, décompression, DCC, lecture courte) : proposent « Verify / repair files » */
export function looksCorrupt(error: string): boolean {
  return /signature|invalide|invalid|corrupt|inflate|décompress|decompress|bzip|checksum|Short read|MPQ|DCC|DC6|DS1|truncated|unexpected end|out of range|hors limites/i.test(error);
}

/**
 * État de la copie : deux fichiers alternés (a, b) portant un numéro de séquence ; une écriture coupée net (rechargement, plantage)
 * laisse l'autre intact. Renvoie l'état valide le plus récent, ou {} (jamais d'exception).
 */
export function parseCopyState(a: string | null, b: string | null): { seq: number; state: CopyState } {
  let best = { seq: -1, state: {} as CopyState };
  for (const t of [a, b]) {
    if (!t) continue;
    try {
      const j = JSON.parse(t) as { seq?: number; state?: CopyState };
      if (typeof j.seq === 'number' && j.state && typeof j.state === 'object' && j.seq > best.seq) best = { seq: j.seq, state: j.state };
    } catch {
      /* écriture interrompue : ignoré */
    }
  }
  return best;
}

