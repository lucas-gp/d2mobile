export const REQUIRED_MPQ = ['d2data.mpq', 'd2char.mpq', 'd2exp.mpq'] as const;
const PATCH_RE = /^(patch_d2|pd2.*|.*patch.*)\.mpq$/i;

export interface ArchiveReport {
  /** les trois archives de base sont présentes et lisibles */
  ok: boolean;
  missing: string[];
  invalid: string[];
  /** patch PD2 / Patch_D2.mpq : facultatifs */
  hasPatch: boolean;
  hasPatchD2: boolean;
  /** messages en français, prêts à afficher */
  messages: string[];
}

/** Entrée : noms (et tailles) des fichiers choisis ; `invalid` = ceux dont l'en-tête n'est pas celui d'un MPQ */
export function archiveReport(files: { name: string; size: number }[], invalid: string[] = []): ArchiveReport {
  const names = new Map(files.map((f) => [f.name.toLowerCase(), f]));
  const bad = new Set(invalid.map((n) => n.toLowerCase()));
  const missing: string[] = [];
  const messages: string[] = [];
  for (const req of REQUIRED_MPQ) {
    const f = names.get(req);
    if (!f) {
      missing.push(req);
      messages.push(`Missing file: ${req}.`);
    } else if (bad.has(req) || f.size < 1024) {
      missing.push(req);
      messages.push(`Unreadable file: ${req} (not a valid MPQ archive, or the file is truncated).`);
    }
  }
  const invalidOut = files.filter((f) => bad.has(f.name.toLowerCase()) && !(REQUIRED_MPQ as readonly string[]).includes(f.name.toLowerCase())).map((f) => f.name);
  for (const n of invalidOut) messages.push(`Ignored file: ${n} (unreadable MPQ archive).`);
  const hasPatchD2 = names.has('patch_d2.mpq') && !bad.has('patch_d2.mpq');
  const hasPatch = [...names.keys()].some((n) => PATCH_RE.test(n) && !bad.has(n));
  if (!missing.length) {
    if (!hasPatchD2) messages.push('Patch_D2.mpq not provided: Diablo II maps will have no placed monsters (optional).');
    if (!hasPatch) messages.push('No Project Diablo 2 patch: recommended to get the mod graphics (optional).');
  }
  return { ok: missing.length === 0, missing, invalid: invalidOut, hasPatch, hasPatchD2, messages };
}

/**
 * Parmi des fichiers choisis (sélection multiple ou dossier d'installation entier), ne garde que les archives utiles : les trois
 * archives requises et les patchs (Patch_D2, Project Diablo 2). Les gros fichiers audio / vidéo (d2music, d2speech, d2video…) sont
 * ignorés : ils ne servent pas aux graphismes et doubleraient l'espace nécessaire. Un nom en double (sous-dossiers) garde le plus gros.
 */
export function relevantMpq<T extends { name: string; size: number }>(files: T[]): { used: T[]; ignored: string[] } {
  const best = new Map<string, T>();
  const ignored: string[] = [];
  for (const f of files) {
    const n = f.name.toLowerCase();
    const useful = (REQUIRED_MPQ as readonly string[]).includes(n) || PATCH_RE.test(n);
    if (!useful) {
      if (/\.mpq$/i.test(n)) ignored.push(f.name);
      continue;
    }
    const prev = best.get(n);
    if (!prev || f.size > prev.size) best.set(n, f);
  }
  return { used: [...best.values()], ignored };
}

