/** Quelle carte et quel palier un chemin `maps/…` désigne (null pour tout autre chemin) */
export function mapOfPath(path: string): MapPath | null {
  if (path === 'maps/index.json') return { kind: 'index', id: '' };
  let m = /^maps\/([a-z0-9_]+)\.json$/.exec(path);
  if (m) return { kind: 'json', id: m[1] };
  // sol : <id>-g<n>.png (hi) / <id>-g<n>-lo.png ; atlas : <id>-t<n>.png (hi) / <id>-tlo-<n>.png
  m = /^maps\/([a-z0-9_]+)-g\d+(-lo)?\.png$/.exec(path);
  if (m) return { kind: 'png', id: m[1], tier: m[2] ? 'lo' : 'hi' };
  m = /^maps\/([a-z0-9_]+)-t(lo-)?\d+\.png$/.exec(path);
  if (m) return { kind: 'png', id: m[1], tier: m[2] ? 'lo' : 'hi' };
  return null;
}

/** Lot « extras » qui produit ce chemin, ou null (planches, cartes, audio…) */
