export interface GenJob {
  key: string;
  id: string;
  tier: Tier;
  prio: number;
  seq: number;
  waiters: ((ok: boolean) => void)[];
}

/**
 * File des générations demandées : une seule entrée par (asset, palier) — une demande en double rejoint l'existante et peut la remonter —,
 * ordre par priorité puis par ancienneté, annulation des demandes pas encore parties. Le travail en cours n'est pas interruptible.
 */
export class GenQueue {
  private jobs = new Map<string, GenJob>();
  private seq = 0;
  /** travaux partis, pas encore terminés */
  private running = new Map<string, GenJob>();

  static keyOf(id: string, tier: Tier): string {
    return `${id}|${tier}`;
  }

  /** Ajoute (ou remonte) une demande ; la promesse vaut true à la fin de la génération, false si elle échoue ou est annulée */
  add(id: string, tier: Tier, prio: number): Promise<boolean> {
    const key = GenQueue.keyOf(id, tier);
    const run = this.running.get(key);
    const ex = this.jobs.get(key) ?? run;
    if (ex) {
      if (!run && prio < ex.prio) ex.prio = prio;
      return new Promise((res) => ex.waiters.push(res));
    }
    return new Promise((res) => {
      this.jobs.set(key, { key, id, tier, prio, seq: this.seq++, waiters: [res] });
    });
  }

  /** Remonte une demande en attente (sans ajouter d'écouteur) ; sans effet si elle est déjà en cours ou plus urgente */
  bump(id: string, tier: Tier, prio: number): void {
    const j = this.jobs.get(GenQueue.keyOf(id, tier));
    if (j && prio < j.prio) j.prio = prio;
  }

  has(id: string, tier: Tier): boolean {
    const k = GenQueue.keyOf(id, tier);
    return this.jobs.has(k) || this.running.has(k);
  }

  /** Demande en attente ou en cours pour cet asset (n'importe quel palier) */
  hasAny(id: string): boolean {
    return this.has(id, 'hi') || this.has(id, 'lo');
  }

  get pending(): number {
    return this.jobs.size;
  }

  get active(): number {
    return this.running.size;
  }

  /** Retire la demande la plus urgente (parmi celles que `accept` laisse passer) et la marque « en cours » */
  next(accept?: (j: GenJob) => boolean): GenJob | undefined {
    let best: GenJob | undefined;
    for (const j of this.jobs.values()) {
      if (accept && !accept(j)) continue;
      if (!best || j.prio < best.prio || (j.prio === best.prio && j.seq < best.seq)) best = j;
    }
    if (!best) return undefined;
    this.jobs.delete(best.key);
    this.running.set(best.key, best);
    return best;
  }

  /** Fin d'un travail : réveille ceux qui attendent */
  finish(job: GenJob, ok: boolean): void {
    this.running.delete(job.key);
    for (const w of job.waiters.splice(0)) w(ok);
  }

  /** Annule les demandes en attente (pas celles en cours) pour lesquelles `pred` est vrai ; renvoie leur nombre */
  cancel(pred: (j: GenJob) => boolean): number {
    let n = 0;
    for (const [k, j] of [...this.jobs]) {
      if (!pred(j)) continue;
      this.jobs.delete(k);
      for (const w of j.waiters.splice(0)) w(false);
      n++;
    }
    return n;
  }

  /** Annule ce qui est moins urgent que `prio` (>) et plus urgent que `below` (<), hors de `keep` : changement de zone (le fond n'est pas touché) */
  cancelAbove(prio: number, keep?: ReadonlySet<string>, below = Infinity): number {
    return this.cancel((j) => j.prio > prio && j.prio < below && !keep?.has(j.id));
  }

  /** Nombre de travaux en cours dont la priorité est au moins `prio` (moins urgents) */
  runningFrom(prio: number): number {
    let n = 0;
    for (const j of this.running.values()) if (j.prio >= prio) n++;
    return n;
  }

  /** Liste (urgence puis ancienneté) des demandes en attente */
  snapshot(): { id: string; tier: Tier; prio: number }[] {
    return [...this.jobs.values()].sort((a, b) => a.prio - b.prio || a.seq - b.seq).map((j) => ({ id: j.id, tier: j.tier, prio: j.prio }));
  }
}

