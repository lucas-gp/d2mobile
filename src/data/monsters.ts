/**
 * Fidélité à Diablo II (monsters-fidelity.ts, généré d'après MonStats.txt ; valeurs PD2 : patch du mod) : les résistances, variantes d'immunité,
 * régénération et Drain remplacent les valeurs écrites plus haut ; les boss prennent leur vie et leurs dégâts par difficulté.
 * Les dégâts A1 des boss qui frappent surtout par compétences (Anciens : Tourbillon, Bond) ne sont pas repris.
 */
function applyFidelity(m: MonsterDef): void {
  const f = MONSTER_FIDELITY[m.id];
  if (!f) return;
  m.res = f.res;
  m.resVariants = f.resVariants;
  m.regen = f.regen;
  m.drain = f.drain;
  if (f.hpD) m.hpD = f.hpD;
  if (f.dmgD && Math.min(...f.dmgD) >= 0.5) m.dmgD = f.dmgD;
}

/**
 * Fidélité, puis durées d'animation d'attaque et de sort d'après animdata.d2 (au lieu des 14/16/18 trames génériques), une fois par
 * monstre : ceux de la base tout de suite, ceux qu'un mod ajoute après l'enregistrement des mods (src/mods/derived.ts) ; un patch de mod
 * sur un monstre de la base, appliqué après, prime. Une entrée de fidélité qu'un mod a patchée (registre `monsterFidelity`) est
 * réappliquée à son monstre après l'enregistrement des mods.
 */
const prepared = new WeakMap<MonsterDef, string>();
const fidelityOf = (m: MonsterDef): string => JSON.stringify(MONSTER_FIDELITY[m.id] ?? null);
function prepareMonsters(): void {
  for (const m of MONSTERS) {
    const seen = prepared.get(m);
    if (seen === undefined) {
      prepared.set(m, fidelityOf(m));
      applyFidelity(m);
      applyAnimTiming(m);
    } else if (seen !== fidelityOf(m)) {
      prepared.set(m, fidelityOf(m));
      applyFidelity(m);
    }
  }
}
prepareMonsters();
afterRegister('fidélité et animations des monstres', prepareMonsters);

