export const BASE_BY_ID: Record<string, ItemBase> = Object.fromEntries(BASES.map((b) => [b.id, b]));

/** Registre des bases (src/mods) : BASES et BASE_BY_ID modifiés sur place, gelés après l'activation du jeu de règles */
export const BASE_REGISTRY = new Registry<ItemBase>('bases', BASES, BASE_BY_ID);

/** Bases de la base du jeu déclarées par les modules annexes (index.ts) ; refusé après l'activation */
export function registerBases(list: ItemBase[]): void {
  for (const b of list) {
    if (BASE_BY_ID[b.id]) throw new Error(`Base en double : ${b.id}`);
    BASE_REGISTRY.add(BASE_MOD_ID, b);
  }
}

