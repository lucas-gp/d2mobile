/** Entrée du catalogue de la base : palier d'un unique ou d'un objet de set, paliers d'un mot runique, châsses minimales d'une base ; aucune monnaie */
export function baseCatalogValue(kind: 'unique' | 'set' | 'runeword' | 'base' | 'currency', id: string): number | readonly [number, number] | undefined {
  if (kind === 'unique') return VALUE_UNIQUES[id];
  if (kind === 'set') return VALUE_SET_ITEMS[id];
  if (kind === 'runeword') return VALUE_RUNEWORDS[id];
  if (kind === 'base') return VALUE_BASES[id];
  // monnaies : palier selon le prix (sim/loot/filter.ts)
  return undefined;
}
