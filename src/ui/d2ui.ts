/**
 * Art d'interface importé de Diablo II (tools/d2import/export-ui.ts) : fond et logo de l'écran de sélection, panneaux, globes, boutons.
 * Chargé une fois le dossier D2 déverrouillé ; sans lui, `d2Ui()` renvoie null et l'interface d'origine reste en place.
 * Chaque image devient une variable CSS `--u-<nom>` (url) et un attribut de `<html>` (`data-d2ui`), pour que la feuille de style
 * n'ait qu'un jeu de règles « D2 » à activer.
 */
import { UI_REQUIRED } from '../../tools/d2import/ui-keys';

export interface UiImage {
  url: string;
  w: number;
  h: number;
  /** bandes d'animation : nombre d'images, colonnes, taille d'une image */
  frames?: number;
  cols?: number;
  cw?: number;
  ch?: number;
  /** ancre des bandes de personnages : position du point de référence (pieds) dans une case */
  ax?: number;
  ay?: number;
}

const images = new Map<string, UiImage>();

export function d2Ui(name: string): UiImage | null {
  return images.get(name) ?? null;
}

/**
 * Placement of the halves of the logo's fire in the art of revision 1 (`logo-fire`, 15 cells of 370 × 170, lot 270 and before): each
 * half was put at the cell's bottom, the left one at x 0 and the right one 2 px before the left one's width, so that the letters jumped
 * from one frame to the next. For each frame drawn (one in two of D2LogoFireLeft / Right), the halves' size and their offsets around
 * the logo's anchor (the DC6 headers of Diablo II 1.13c, the same in every copy of the game): [left w, h, ox, oy, right w, h, ox, oy].
 * Lot 298 (owner, a Galaxy Z Fold: "no animation at all on the DIABLO logo"): art generated by an earlier version is of revision 1, whose logo was
 * shown still; it is now rebuilt at load at the right places (`legacyLogo`), the fire animated and the letters fixed.
 */
export const LEGACY_LOGO: readonly (readonly number[])[] = [
  [170, 155, -174, -102, 174, 148, 0, -94],
  [170, 148, -174, -95, 174, 150, 0, -96],
  [173, 156, -178, -102, 176, 151, 1, -96],
  [175, 163, -178, -110, 177, 146, 2, -92],
  [173, 155, -175, -102, 182, 146, -4, -92],
  [173, 156, -175, -102, 183, 145, -4, -91],
  [174, 155, -177, -102, 180, 149, -3, -95],
  [174, 156, -180, -102, 181, 150, -1, -96],
  [170, 163, -176, -109, 174, 162, 2, -108],
  [170, 155, -176, -102, 176, 146, -1, -92],
  [173, 155, -178, -102, 177, 145, -1, -91],
  [170, 156, -176, -102, 175, 149, 1, -95],
  [176, 155, -180, -102, 176, 147, 4, -93],
  [178, 155, -180, -102, 176, 169, 3, -109],
  [177, 156, -179, -102, 183, 148, -4, -94],
];
/** The cells of revision 2's logo: 360 × 170, the anchor at (180, 110) */
const LOGO_CELL = { cw: 360, ch: 170, ax: 180, ay: 110 };

/**
 * Source and destination rectangles of each half of each frame, from revision 1's sheet (cells of `cw` × `ch`, 5 columns) to revision
 * 2's (cells of 360 × 170 around the anchor): [sx, sy, w, h, dx, dy] (pure: unit tested)
 */
export function legacyLogoRects(cw = 370, ch = 170): [number, number, number, number, number, number][][] {
  return LEGACY_LOGO.map((f, i) => {
    const [wl, hl, oxl, oyl, wr, hr, oxr, oyr] = f;
    const cx = (i % 5) * cw;
    const cy = Math.floor(i / 5) * ch;
    const nx = (i % 5) * LOGO_CELL.cw;
    const ny = Math.floor(i / 5) * LOGO_CELL.ch;
    return [
      [cx, cy + ch - hl, wl - 2, hl, nx + oxl + LOGO_CELL.ax, ny + oyl + LOGO_CELL.ay],
      [cx + wl - 2, cy + ch - hr, Math.min(wr, cw - wl + 2), hr, nx + oxr + LOGO_CELL.ax, ny + oyr + LOGO_CELL.ay],
    ];
  });
}

/** Revision 1's `logo-fire` (15 cells of 370 × 170) rebuilt as revision 2's `logo` (the fire's halves at their places); null if it cannot */
export async function legacyLogo(old: UiImage): Promise<UiImage | null> {
  if (old.w !== 1850 || old.h !== 510 || typeof document === 'undefined') return null;
  const img = new Image();
  img.src = old.url;
  await img.decode();
  const cv = document.createElement('canvas');
  cv.width = LOGO_CELL.cw * 5;
  cv.height = LOGO_CELL.ch * 3;
  const g = cv.getContext('2d');
  if (!g) return null;
  for (const frame of legacyLogoRects()) {
    // each frame within its own cell (a half never spills over the next one)
    for (const [sx, sy, w, h, dx, dy] of frame) g.drawImage(img, sx, sy, w, h, dx, dy, w, h);
  }
  const blob = await new Promise<Blob | null>((res) => cv.toBlob(res, 'image/png'));
  if (!blob) return null;
  return { url: URL.createObjectURL(blob), w: cv.width, h: cv.height, frames: 15, cols: 5, ...LOGO_CELL };
}

/**
 * Diablo II logo: animated fire over static letters (`logo`, anchored at the point the game places at (400, 120) on its 800 × 600 menu).
 * Interface art generated before revision 2 only has `logo-fire`, whose frames were misplaced (the letters jumped): rebuilt at load
 * (`legacyLogo`, lot 298); until then (or if it cannot be) its first frame is shown, still.
 */
export function d2Logo(): UiImage | null {
  const logo = images.get('logo');
  if (logo) return logo;
  const old = images.get('logo-fire');
  return old ? { ...old, frames: 1, ax: 174, ay: 118 } : null;
}

export function d2UiCount(): number {
  return images.size;
}

export function d2UiReady(): boolean {
  return images.size > 0;
}

/** Dernière lecture de l'interface : attendu (index), chargé, absent du cache, indispensables manquants — diagnostic de l'écran d'attente */
export interface UiLoadInfo {
  indexed: number;
  loaded: number;
  notInCache: string[];
  missingRequired: string[];
  indexError: string;
}
let lastLoad: UiLoadInfo = { indexed: 0, loaded: 0, notInCache: [], missingRequired: [...UI_REQUIRED], indexError: 'not read yet' };
export function d2UiLoadInfo(): UiLoadInfo {
  return lastLoad;
}

export async function loadD2Ui(read: (path: string) => Promise<Uint8Array | null>): Promise<number> {
  const info: UiLoadInfo = { indexed: 0, loaded: 0, notInCache: [], missingRequired: [], indexError: '' };
  try {
    const raw = await read('ui/ui.json');
    if (!raw) {
      info.indexError = 'ui/ui.json not in cache';
      return 0;
    }
    const index = JSON.parse(new TextDecoder().decode(raw)) as { files: Record<string, Omit<UiImage, 'url'>> };
    info.indexed = Object.keys(index.files).length;
    await Promise.all(
      Object.entries(index.files).map(async ([name, info2]) => {
        const png = await read(`ui/${name}.png`);
        if (!png) {
          info.notInCache.push(name);
          return;
        }
        const url = URL.createObjectURL(new Blob([png as BlobPart], { type: 'image/png' }));
        images.set(name, { ...info2, url });
        document.documentElement.style.setProperty(`--u-${name}`, `url("${url}")`);
        document.documentElement.style.setProperty(`--u-${name}-w`, `${info2.w}px`);
        document.documentElement.style.setProperty(`--u-${name}-h`, `${info2.h}px`);
      }),
    );
    // lot 298: art of revision 1 (a pack never generated again): its logo rebuilt, animated
    const old = images.get('logo-fire');
    if (old && !images.has('logo')) {
      const fixed = await legacyLogo(old).catch(() => null);
      if (fixed) images.set('logo', fixed);
    }
    if (images.size) document.documentElement.dataset.d2ui = '1';
    return images.size;
  } catch (e) {
    info.indexError = (e as Error).message;
    return 0;
  } finally {
    info.loaded = images.size;
    info.missingRequired = UI_REQUIRED.filter((k) => !images.has(k));
    lastLoad = info;
  }
}

/** Éléments animés (bande d'images) : un seul minuteur pour tous, les éléments retirés de la page sont oubliés */
const animated = new Set<{ el: HTMLElement; img: UiImage; scale: number; start: number }>();
let ticker = 0;

function tick(): void {
  const now = performance.now();
  for (const a of animated) {
    if (!a.el.isConnected) {
      animated.delete(a);
      continue;
    }
    const { img } = a;
    const n = img.frames ?? 1;
    const f = Math.floor(((now - a.start) / 1000) * 12) % n;
    const cols = img.cols ?? 1;
    const cw = img.cw ?? img.w;
    const ch = img.ch ?? img.h;
    a.el.style.backgroundPosition = `${-(f % cols) * cw * a.scale}px ${-Math.floor(f / cols) * ch * a.scale}px`;
  }
  ticker = animated.size ? requestAnimationFrame(tick) : 0;
}

/** Élément affichant une bande d'images D2 animée (12 images/s) à l'échelle voulue ; null si l'image n'est pas disponible */
export function animatedSprite(name: string, scale = 1): HTMLElement | null {
  const img = name === 'logo' ? d2Logo() : d2Ui(name);
  if (!img) return null;
  const el = document.createElement('div');
  const cw = img.cw ?? img.w;
  const ch = img.ch ?? img.h;
  el.className = 'd2-anim';
  el.style.width = `${cw * scale}px`;
  el.style.height = `${ch * scale}px`;
  el.style.backgroundImage = `url("${img.url}")`;
  el.style.backgroundSize = `${img.w * scale}px ${img.h * scale}px`;
  el.style.imageRendering = 'pixelated';
  animated.add({ el, img, scale, start: performance.now() });
  if (!ticker) ticker = requestAnimationFrame(tick);
  return el;
}
