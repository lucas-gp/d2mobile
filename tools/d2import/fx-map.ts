/**
 * Effets de sorts de Diablo II (missiles et overlays DCC) pour le jeu. Chaque entrée devient une planche `fx_<id>` (une animation « idle »,
 * une ou plusieurs directions) ; le rendu les pose sur les projectiles, les impacts, les zones et les lanceurs (src/render/fx.ts).
 * `blend` : add = lumière (feu, glace, foudre : le noir est invisible), normal = objet solide (flèches, os, rochers).
 * `fps` : cadence (D2 : AnimRate 16 = une image par tic de 25 i/s).
 */
export interface FxSpec {
  id: string;
  /** chemin sous data\global\ (sans extension) */
  file: string;
  blend: 'add' | 'normal';
  fps?: number;
  loop?: boolean;
  /** garde une image sur n (effets très longs) */
  thin?: number;
}

const M = (id: string, name: string, extra: Partial<FxSpec> = {}): FxSpec => ({ id, file: `missiles\\${name}`, blend: 'add', loop: false, ...extra });
const O = (id: string, name: string, extra: Partial<FxSpec> = {}): FxSpec => ({ id, file: `overlays\\${name}`, blend: 'add', loop: false, ...extra });

